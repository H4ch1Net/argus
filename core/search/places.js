/** Lowercase, accents stripped, apostrophes dropped, other punctuation to spaces, "saint" to "st". */
export function normalizePlaceName(s) {
  return String(s ?? '')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/['’`]/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .replace(/\bsaint\b/g, 'st');
}

