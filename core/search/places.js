const label = (name, country) =>
  country && country !== name ? `${name}, ${country}` : name;

// Precomputed search keys, one per row.
const INDEX = CITIES.map(([name, lat, lon, rank, country], i) => ({
  i,
  name,
  country,
  lat,
  lon,
  rank,
  n: normalizePlaceName(name),
  nc: normalizePlaceName(`${name} ${country}`),
}));
const ALIAS_INDEX = new Map(
  Object.entries(ALIASES).map(([alias, [name, country]]) => [
    alias,
    INDEX.find((p) => p.name === name && p.country === country),
  ]),
);

function toResult(p, score) {
  return {
    name: label(p.name, p.country),
    latitude: p.lat,
    longitude: p.lon,
    rank: p.rank,
    exact: score === 0,
    source: 'offline',
  };
}

/**
 * Offline place search. Exact names, "name, country" and aliases score first,
 * then name prefixes, then word prefixes; ties go to the larger place.
 * @param {string} query
 * @param {{ limit?: number }} [opts]
 * @returns {Array<{ name: string, latitude: number, longitude: number, rank: number,
 *   exact: boolean, source: 'offline' }>}
 */
export function searchPlaces(query, { limit = 5 } = {}) {
  const q = normalizePlaceName(query);
  if (q.length < 2) return [];
  const scored = new Map();
  const hit = (p, score) => {
    if (p && (!scored.has(p.i) || scored.get(p.i) > score)) scored.set(p.i, score);
  };
  hit(ALIAS_INDEX.get(q), 0);
  if (q.length >= 3 || scored.size === 0) {
    for (const p of INDEX) {
      if (p.n === q || p.nc === q) hit(p, 0);
      else if (p.n.startsWith(q) || p.nc.startsWith(q)) hit(p, 1);
      else if (q.length >= 3 && p.n.split(' ').some((w) => w.startsWith(q))) hit(p, 2);
    }
  }
  return [...scored.entries()]
    .map(([i, score]) => ({ p: INDEX[i], score }))
    .sort(
      (a, b) =>
        a.score - b.score ||
        a.p.rank - b.p.rank ||
        a.p.name.length - b.p.name.length ||
        a.p.name.localeCompare(b.p.name),
    )
    .slice(0, Math.max(0, limit))
    .map(({ p, score }) => toResult(p, score));
}

/** The bundled place a query names exactly (name, "name, country" or alias), or null. */
export function findPlace(query) {
  const [first] = searchPlaces(query, { limit: 1 });
  return first?.exact ? first : null;
}
